import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { applyKnowledge, inspectKnowledge } from '../src/knowledge.mjs';
import { readState } from '../src/store.mjs';
import { deliver, emit, event, fixture, git, identity, start } from './helpers.mjs';

test('V03 临时本地 Git 远端：指定提交 push、快进 pull、查看为 operation-only，用户未提交文件保留', async () => {
  const f = await fixture({ git: true });
  const remote = path.join(f.area, 'remote.git');
  git(f.project, ['init', '--bare', remote]);
  git(f.project, ['add', 'README.md']);
  git(f.project, ['commit', '-m', 'fixture baseline']);
  git(f.project, ['remote', 'add', 'origin', remote]);
  await writeFile(path.join(f.project, 'user-note.txt'), '用户未提交内容');
  await start(f, { mode: 'read-only', allowedPaths: [] });
  await emit(f, { action: 'phase', phase: 'operation-only' });
  git(f.project, ['push', '-u', 'origin', 'main']);
  const second = path.join(f.area, 'second');
  git(f.project, ['clone', '-b', 'main', remote, second]);
  await writeFile(path.join(second, 'upstream.txt'), '远端新提交');
  git(second, ['add', 'upstream.txt']);
  git(second, ['commit', '-m', 'upstream change']);
  git(second, ['push', 'origin', 'main']);
  git(f.project, ['pull', '--ff-only', 'origin', 'main']);
  assert.equal(git(f.project, ['rev-parse', 'HEAD']), git(second, ['rev-parse', 'HEAD']));
  assert.ok(git(f.project, ['status', '--short']).includes('user-note.txt'));
  assert.equal(await readFile(path.join(f.project, 'user-note.txt'), 'utf8'), '用户未提交内容');
  await assert.rejects(readFile(path.join(f.project, 'LESSONS.md')), { code: 'ENOENT' });
  assert.deepEqual(await event(f, 'Stop'), {});
  assert.equal(Object.values((await readState(f.directory)).pending).length, 0);
});
test('V12 反证修订旧经验、快照可追溯、下一任务读到新条件（合成角色交接，不冒充真实代理）', async () => {
  const f = await fixture();
  const old = '# 恢复经验\n旧版本同步恢复后立即聚焦。\n';
  await writeFile(path.join(f.project, 'LESSONS.md'), old);
  await start(f);
  const before = await inspectKnowledge(f.directory, f.project, 'LESSONS.md');
  const candidate = { id: 'async-counterevidence', taskId: f.taskId, workPackage: 'sample-window', conditions: '当前版本改为异步恢复', finding: '旧同步经验会使迟到响应覆盖焦点', recommendation: '等待完成并核对请求编号，旧经验退出当前正文', evidence: ['synthetic:实现入口差异', 'synthetic:Reviewer核对因果'] };
  const tx = await applyKnowledge(f.directory, { ...await identity(f), candidates: [candidate], changes: [{ path: 'LESSONS.md', baseline: before.fingerprint, content: '# 恢复经验\n当前异步版本：等待完成并核对请求编号后聚焦。旧同步条目被当前异步实现反证，旧正文保存在本次事务前快照。\n', responsibility: '有条件的项目经验', reason: '当前实现反证旧条件', evidence: candidate.evidence, candidateIds: [candidate.id] }] });
  assert.equal(tx.status, 'applied');
  assert.equal(await readFile(tx.files[0].snapshot, 'utf8'), old);
  await deliver(f, { status: 'updated', transactionIds: [tx.transactionId] });
  assert.deepEqual(await event(f, 'Stop'), {});
  await emit(f, { action: 'task-end' });
  f.turnId = 'followup-turn';
  f.taskId = 'followup-task';
  await event(f, 'UserPromptSubmit');
  await start(f, { mode: 'read-only', allowedPaths: [] });
  const next = await inspectKnowledge(f.directory, f.project, 'LESSONS.md');
  assert.ok(next.content.includes('当前异步版本'));
  assert.ok(next.content.includes('反证'));
});
